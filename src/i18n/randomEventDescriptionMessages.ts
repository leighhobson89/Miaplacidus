export function randomEventDescriptionTemplate(
  locale: LocaleId,
  key: RandomEventDescriptionKey,
  values: Readonly<Record<string, string>> = {},
): string {
  return messages[locale][key].replace(/\{([^{}]+)\}/g, (placeholder, name: string) =>
    values[name] ?? placeholder,
  );
}

